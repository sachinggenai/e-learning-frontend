// ─── Lookup Helpers ──────────────────────────────────────────────

export function getComponentTypesByCategory(categoryId: string): ComponentTypeDetail[] {
  return ALL_COMPONENT_TYPES.filter(t => t.category === categoryId);
}

export function getComponentTypeById(typeId: string): ComponentTypeDetail | undefined {
  return ALL_COMPONENT_TYPES.find(t => t.typeId === typeId);
}

export function searchComponentTypes(query: string): ComponentTypeDetail[] {
  const q = query.toLowerCase();
  return ALL_COMPONENT_TYPES.filter(t =>
    t.displayName.toLowerCase().includes(q) ||
    t.description.toLowerCase().includes(q) ||
    t.tags.some(tag => tag.toLowerCase().includes(q)) ||
    t.category.toLowerCase().includes(q)
  );
}

export function componentTypeListResponse(
  types: ComponentTypeSummary[],
  page = 1,
  limit = 50,
): ComponentTypeListResponse {
  const start = (page - 1) * limit;
  return {
    items: types.slice(start, start + limit),
    total: types.length,
    page,
    limit,
  };
}
