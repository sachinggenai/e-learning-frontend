// ─── Helper to build ComponentTypeDetail ─────────────────────────

function ct(
  typeId: string,
  category: string,
  displayName: string,
  description: string,
  icon: string,
  tags: string[],
  completionCapabilities: Array<'view' | 'interact' | 'audio' | 'score' | 'custom'>,
  scoringEnabled: boolean,
  audioSupport: { perComponent: boolean; perInteraction: boolean; interactionPoints?: string[] | null },
  defaultData: Record<string, any>,
  sortOrder: number,
  extras?: Partial<ComponentTypeDetail>,
): ComponentTypeDetail {
  return {
    typeId,
    category,
    displayName,
    description,
    icon,
    tags,
    completionCapabilities,
    scoringEnabled,
    audioSupport,
    estimatedDuration: extras?.estimatedDuration ?? null,
    thumbnail: extras?.thumbnail ?? null,
    schema: extras?.schema ?? {},
    defaultData,
    defaultCompletionType: completionCapabilities[0] ?? 'view',
    maxScore: extras?.maxScore ?? (scoringEnabled ? 100 : null),
    scoringRules: extras?.scoringRules ?? null,
    sortOrder,
    isActive: true,
    createdAt: '2026-01-01T00:00:00Z',
    updatedAt: '2026-02-14T00:00:00Z',
  };
}

